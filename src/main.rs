// В релизе окно консоли не нужно — приложение графическое.
#![cfg_attr(not(debug_assertions), windows_subsystem = "windows")]

mod app;
mod engine;
mod fonts;
mod i18n;
mod model;
mod motion;
mod theme;

use eframe::egui;

fn main() -> eframe::Result {
    let options = eframe::NativeOptions {
        viewport: egui::ViewportBuilder::default()
            // Размер до разворачивания: к нему окно вернётся, когда
            // пользователь нажмёт «Восстановить».
            //
            // Разворачивает окно `app.rs`, однократной командой на первом
            // кадре, а `with_maximized(true)` здесь не ставится. До eframe 0.37
            // флаг вместе с `with_inner_size` выставлял окну лишь признак
            // развёрнутого, не меняя геометрию (`IsZoomed` отвечал
            // «развёрнуто», а окно оставалось 720×560), и команда после него
            // становилась пустой операцией. В 0.37 развёртывают оба способа
            // (проверено вживую 2026-10-26), но держать два способа на одно
            // дело незачем: вместе они однажды уже съели друг друга.
            .with_inner_size([720.0, 560.0])
            .with_min_inner_size([520.0, 420.0]),
        ..Default::default()
    };

    eframe::run_native(
        "Savio",
        options,
        Box::new(|cc| {
            // Шрифты ставятся один раз и навсегда: `set_fonts` пересобирает
            // атлас глифов, и повторять это при смене темы было бы подвисанием
            // на ровном месте. Стиль же зависит от выбранной темы, а её знают
            // только настройки, прочитанные внутри `SavioApp::new`, — поэтому
            // `theme::apply` зовёт оно само.
            theme::install_fonts(&cc.egui_ctx);
            // Контекст нужен приложению, чтобы поток установки мог будить
            // окно на перерисовку.
            let mut app = app::SavioApp::new(&cc.egui_ctx);
            // Без этого окно шире или выше 8192 точек убивает процесс вместе
            // с идущей загрузкой, причём в релизе молча. Подробности — у
            // `GpuErrors` в app.rs.
            app.catch_gpu_errors(cc);
            // Здесь же, пока состояние отрисовки под рукой, забираем сведения
            // о видеокарте для вкладки «Система»: адаптер уже открыт, и
            // спрашивать его позже было бы неоткуда.
            app.read_gpu_info(cc);
            Ok(Box::new(app))
        }),
    )
}
