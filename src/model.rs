    const TEN_MINUTES: Option<f64> = Some(600.0);

    /// Короткий кусок берётся у yt-dlp, длинный — своим ffmpeg из целого
    /// ролика. Порог — половина, и проверяются обе стороны от него: правило
    /// с одной проверкой прошло бы и на «всегда медленно», и на «всегда
    /// целиком», а это ровно те две поломки, которых надо избежать.
    #[test]
    fn a_long_section_switches_to_the_fast_path() {
        // Ниже половины — прежний путь.
        assert_eq!(
            section(Some(60), Some(90)).plan(TEN_MINUTES),
            SectionPlan::Stream
        );
        assert_eq!(
            section(Some(0), Some(299)).plan(TEN_MINUTES),
            SectionPlan::Stream
        );

        // Ровно половина и выше — качаем целиком и режем сами.
        assert_eq!(
            section(None, Some(300)).plan(TEN_MINUTES),
            SectionPlan::CutAfter
        );
        assert_eq!(
            section(Some(60), Some(560)).plan(TEN_MINUTES),
            SectionPlan::CutAfter
        );
    }

    /// Открытый конец — это «до конца ролика», и длину куска надо считать
    /// от длительности. Без этого «с 1:00 и до конца» у десятиминутного
    /// ролика выглядело бы фрагментом неизвестной длины и всегда уходило
    /// бы медленным путём — то есть ровно тот случай, ради которого задача
    /// и делалась, остался бы непочиненным.
    #[test]
    fn an_open_end_is_measured_against_the_duration() {
        assert_eq!(
            section(Some(60), None).plan(TEN_MINUTES),
            SectionPlan::CutAfter
        );
        // Хвост короче половины — прежний путь.
        assert_eq!(
            section(Some(540), None).plan(TEN_MINUTES),
            SectionPlan::Stream
        );
    }

    /// Конец за концом ролика ролика не удлиняет: «с начала по 99:99» —
