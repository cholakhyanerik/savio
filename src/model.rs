// Снимок системы
//
// Здесь только типы отчёта и форматирование. Как эти числа добываются, знает
// `engine::hardware`; каким цветом рисуется статус — `app.rs`. Домен не знает
// ни про то, ни про другое.
//
// Сквозное правило раздела: **«нет значения» — это отдельное состояние, а не
// ноль и не пустая строка.** Опрос железа отказывает молча гораздо чаще, чем
// отвечает отказом, и почти каждый источник подсовывает на месте неизвестного
// правдоподобное число. `sysinfo` при неудавшемся запросе частоты кладёт ноль,
// и «0 МГц» читается как остановившийся процессор. `state_of_health` батареи
// при нулевой проектной ёмкости даёт `NaN`, и в окне появляется «NaN %».
// Windows не сообщает производителя USB-устройства вовсе. Поэтому значение
// строки — `Option<String>`, а `None` рисуется прочерком.
// ---------------------------------------------------------------------------

/// Чем кончился один пункт отчёта.
///
/// Вариантов четыре, а не три, и лишний здесь — `Unknown`. Он нужен потому,
/// что «спросили, а ответа нет» — самый частый исход опроса железа, и свести
/// его больше не к чему. Назвать это `Ok` значит сказать «всё в порядке» про
/// то, чего не смотрели, — худший вид молчаливого отказа: пользователь
/// считает проверку пройденной. Назвать `Failed` — напугать штатным
/// положением дел: счётчика циклов батареи нет на большинстве ноутбуков,
/// и это не поломка.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum CheckStatus {
    /// Спросили, ответили, и ответ хороший.
    Ok,
    /// Ответ есть, и на него стоит посмотреть: кончается место, изношена
    /// батарея.
    Warning,
    /// Спросить не вышло: система ответила отказом.
    Failed,
    /// Спросили, а значения нет. Это не «хорошо» и не «плохо».
    Unknown,
}

impl CheckStatus {
    /// Подпись для плашки статуса.
    pub fn label(self) -> &'static str {
        match self {
            Self::Ok => "В порядке",
            Self::Warning => "Внимание",
            Self::Failed => "Не удалось",
            Self::Unknown => "Нет данных",
        }
    }
}

/// Одна строка подробностей: подпись и значение.
#[derive(Clone, Debug)]
pub struct CheckRow {
    pub label: String,
    /// `None` — система значения не сообщила. Рисуется прочерком.
    pub value: Option<String>,
}

impl CheckRow {
    /// Строка со значением.
    pub fn new(label: impl Into<String>, value: impl Into<String>) -> Self {
        Self {
            label: label.into(),
            value: Some(value.into()),
        }
    }

    /// Строка, у которой значения нет.
    ///
    /// Отдельный конструктор, а не `new(label, "—")`: прочерк рисует UI, и
    /// подставлять его сюда строкой значило бы сделать «нет данных»
    /// неотличимым от значения, которое и правда равно прочерку.
    pub fn missing(label: impl Into<String>) -> Self {
        Self {
            label: label.into(),
            value: None,
        }
    }

    /// Строка из того, что могло не приехать.
    pub fn maybe(label: impl Into<String>, value: Option<String>) -> Self {
        Self {
            label: label.into(),
            value,
        }
    }
}

/// Один пункт отчёта: что смотрели, чем кончилось, что увидели.
#[derive(Clone, Debug)]
pub struct Check {
    /// Заголовок карточки: «Процессор», «Батарея», «USB-устройства».
    pub name: String,
    pub status: CheckStatus,
    /// Итог одной строкой — то, что видно, не вчитываясь в подробности.
    pub summary: String,
    pub rows: Vec<CheckRow>,
    /// Что с этим делать.
    ///
    /// Заполняется **только** там, где беда узнана наверняка. Довод тот же,
    /// что у `explain_failure`: совет не про ту беду хуже отсутствия совета,
    /// потому что человек пойдёт чинить не то. В остальных случаях молчим.
    pub advice: Option<String>,
}

/// Сколько пунктов чем кончилось.
#[derive(Clone, Copy, Default, PartialEq, Eq, Debug)]
pub struct Tally {
    pub ok: usize,
    pub warning: usize,
    pub failed: usize,
    pub unknown: usize,
}

/// Снимок системы целиком.
#[derive(Clone, Debug, Default)]
pub struct SystemReport {
    pub checks: Vec<Check>,
}

impl SystemReport {
    pub fn tally(&self) -> Tally {
        let mut t = Tally::default();
        for check in &self.checks {
            match check.status {
                CheckStatus::Ok => t.ok += 1,
                CheckStatus::Warning => t.warning += 1,
                CheckStatus::Failed => t.failed += 1,
                CheckStatus::Unknown => t.unknown += 1,
            }
        }
        t
    }

    /// Общий итог одной строкой.
    ///
    /// Слов «проблем не найдено» здесь нет и быть не может, даже когда все
    /// пункты в порядке. Отчёт видит малую часть железа, и нехватка прав,
    /// отсутствие датчика и исправная машина дают одинаково пустой ответ —
    /// обещать по такому основанию отсутствие проблем нельзя. Поэтому итог
    /// пересказывает пересчёт, а не выносит приговор.
    pub fn headline(&self) -> String {
        let t = self.tally();
        if self.checks.is_empty() {
            return "Отчёт пуст.".to_owned();
        }

        let mut parts = vec![format!(
            "Пунктов: {} — {} в порядке",
            self.checks.len(),
            t.ok
        )];
        if t.warning > 0 {
            parts.push(format!("{} с замечанием", t.warning));
        }
        if t.failed > 0 {
            parts.push(format!("{} не удалось", t.failed));
        }
        if t.unknown > 0 {
            parts.push(format!("{} без данных", t.unknown));
        }
        format!("{}.", parts.join(", "))
    }

    /// Отчёт простым текстом — то, что ложится в файл.
    ///
    /// Прочерк на месте отсутствующего значения ставится и здесь: файл
    /// человек отправляет в чужие руки, и «нет данных», превратившееся при
    /// сохранении в пустоту, там уже не восстановить.
    pub fn to_text(&self) -> String {
        let mut out = String::from("Отчёт Savio о системе\n");
        out.push_str(&format!("{}\n", self.headline()));

        for check in &self.checks {
            out.push_str(&format!(
                "\n[{}] {}\n  {}\n",
                check.status.label(),
                check.name,
                check.summary
            ));
            for row in &check.rows {
                let value = row.value.as_deref().unwrap_or("—");
                out.push_str(&format!("  {}: {}\n", row.label, value));
            }
            if let Some(advice) = &check.advice {
                out.push_str(&format!("  Совет: {advice}\n"));
            }
        }
        out
    }
}

/// Сведения о видеокарте, снятые с адаптера, которым eframe рисует окно.
