// Монитор производительности
//
// Здесь только типы замера и его форматирование. Как эти числа добываются,
// знает `engine::monitor`; каким цветом рисуется полоска — `app.rs`.
//
// Правило раздела то же, что и у снимка системы: «нет значения» — отдельное
// состояние. Но ловушка здесь противоположная. У снимка ноль почти всегда
// означал молчаливый отказ; у монитора ноль почти всегда законен — простаивающий
// диск и правда читает ноль байт в секунду, и подменять это прочерком значило бы
// врать в другую сторону. Поэтому «нет данных» здесь узнаётся не по самому
// показанию, а по **накопительному** счётчику: суммарные с загрузки байты у
// живой машины нулём не бывают, и ноль в них означает, что счётчиков нет вовсе
// (`IOCTL_DISK_PERFORMANCE` на Windows отвечает отказом, а `sysinfo` оставляет
// в поле ноль — отличить его от простоя по одному показанию нечем).
// ---------------------------------------------------------------------------

/// Сколько замеров помнит график.
///
/// Потолок обязателен по Правилу 1, как `LOG_LIMIT` у журнала и
/// `HISTORY_LIMIT` у истории: монитор, оставленный на ночь, набрал бы за восемь
/// часов почти тридцать тысяч точек на каждый показатель. 120 — это две минуты
/// при секундном опросе: столько и помещается в полоску шириной с карточку,
/// а дальше соседние точки всё равно ложатся в один столбец экрана.
pub const TRACE_LIMIT: usize = 120;

/// Сколько процессов показываем.
///
/// Потолок по той же причине, что и у `USB_LIMIT` в снимке системы: процессов
/// на обычной машине под три сотни, читают из них верхушку, а собирать строки
/// для остальных — работа впустую каждую секунду.
pub const PROC_LIMIT: usize = 12;

/// Кольцевой буфер под график показателя.
///
/// Отдельный тип, а не голый `Vec`, ровно ради потолка — тот же довод, что
/// у `History`: помнить про `truncate` в каждом месте, где в список что-то
/// кладут, ненадёжнее, чем держать предел в одном месте.
#[derive(Clone, Debug, Default)]
pub struct Trace {
    /// Слева самое старое, справа самое свежее — в том же порядке, в каком
    /// график и рисуется. Отсюда `VecDeque`: `Vec::remove(0)` сдвигал бы
    /// сто двадцать чисел каждую секунду.
    values: std::collections::VecDeque<f32>,
}

impl Trace {
    /// Запоминает свежее значение, вытесняя самое старое.
    pub fn push(&mut self, value: f32) {
        // `>=`, а не `==`: предел могли уменьшить между сборками, и буфер,
        // пришедший из прошлой жизни длиннее нового потолка, иначе никогда
        // бы до него не ужался.
        while self.values.len() >= TRACE_LIMIT {
            self.values.pop_front();
        }
        self.values.push_back(value);
    }

    /// Значения от старого к свежему.
    ///
    /// Длину спрашивают у самого обхода (`iter().len()`), а не отдельным
    /// методом: считать её всё равно приходится вместе с обходом, а два
    /// способа спросить одно и то же расходятся тем охотнее, чем реже
    /// в них смотрят.
    pub fn iter(&self) -> impl ExactSizeIterator<Item = f32> + '_ {
        self.values.iter().copied()
    }

    /// Забывает всё. Нужно при перезапуске опроса: между двумя включениями
    /// монитора проходит сколько угодно времени, и склеивать вчерашний
    /// график с сегодняшним значило бы показать провал, которого не было.
    pub fn clear(&mut self) {
        self.values.clear();
    }
}

/// Один показатель: число для графика и та же величина словами.
///
/// Пара, а не одно число: строку собирает движок в момент замера — в кадре
/// отрисовки `format!` запрещён (Правило 1), а показывать надо и то и другое.
/// `percent` и `percent_text` пусты строго вместе, за это отвечает `new`.
#[derive(Clone, Debug, Default)]
pub struct Metric {
    /// Доля в процентах, 0..=100. `None` — система показания не дала.
    pub percent: Option<f32>,
    /// «37%». `None` ровно тогда же, когда и у `percent`.
    pub percent_text: Option<String>,
    /// Подробности под числом: «13.1 ГБ из 31.9 ГБ». `None` — сказать нечего.
    pub detail: Option<String>,
}

impl Metric {
    /// Показатель с известной долей.
    ///
    /// Нечисло сюда попадает не теоретически: доля считается делением, и на
    /// машине, не сообщившей объём памяти, это `0.0 / 0.0`. `human_percent`
    /// такое отсеивает, а вместе с ним обнуляется и число для графика —
    /// иначе `NaN` уехал бы в кольцевой буфер и растянул бы весь масштаб.
    pub fn new(percent: f32, detail: Option<String>) -> Self {
        let percent_text = human_percent(percent);
        Self {
            percent: percent_text.is_some().then_some(percent),
            percent_text,
            detail,
        }
    }

    /// Показатель, доли у которого нет вовсе, — например, выключенная подкачка.
    pub fn missing(detail: Option<String>) -> Self {
        Self {
            percent: None,
            percent_text: None,
            detail,
        }
    }
}

/// Одна строка списка процессов.
///
/// Строки готовы к показу: собираются при замере, а не в кадре. Процессов
/// в списке дюжина, но приезжает он раз в секунду, а рисуется шестьдесят, —
/// собирать их в кадре значило бы делать ту же работу шестьдесят раз подряд
/// с одинаковым исходом.
#[derive(Clone, Debug)]
pub struct ProcRow {
    /// Имя процесса, как его называет система: `chrome.exe`, `ffmpeg`.
    pub name: String,
    /// Доля процессора, 0..=100, — для полоски. Уже поделена на число ядер:
    /// `sysinfo` отдаёт до «100% × число ядер», и на восьмиядерной машине
    /// один занятой процесс показывал бы 800%.
    pub cpu: f32,
    /// «12%»
    pub cpu_text: String,
    /// «1.4 ГБ»
    pub mem_text: String,
}

/// Один замер монитора целиком.
#[derive(Clone, Debug, Default)]
pub struct PerfSample {
    pub cpu: Metric,
    pub mem: Metric,
    /// Подкачка. Выключенная — это `detail` со словом «выключена», а не
    /// прочерк: честный ноль и отсутствие данных здесь разные вещи (так же
    /// устроена карточка памяти в снимке системы).
    pub swap: Metric,
    /// «Приём 1.2 МБ/с · Отдача 128.0 КБ/с». `None` — счётчиков нет.
    pub net: Option<String>,
    /// «Чтение 4.0 МБ/с · Запись 512.0 КБ/с». `None` — счётчиков нет.
    pub disk: Option<String>,
    /// Верхние процессы по загрузке процессора, не длиннее `PROC_LIMIT`.
    pub procs: Vec<ProcRow>,
}

