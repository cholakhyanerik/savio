    /// обнуляет полосу перед каждым файлом, стал бы неотличим от прогресса
    /// первого элемента очереди: UI принял бы чужие нули за её начало.
    #[test]
    fn default_progress_belongs_to_no_download() {
        assert_eq!(NO_DOWNLOAD, 0);
        assert_eq!(Progress::default().download_id, NO_DOWNLOAD);
    }

    #[test]
