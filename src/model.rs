/// Русское склонение при числительном: 1 день, 2 дня, 5 дней.
pub fn plural_ru(n: u64, one: &'static str, few: &'static str, many: &'static str) -> &'static str {
    // Одиннадцать-четырнадцать — исключение: «11 дней», а не «11 день».
    // Без этой проверки правило по последней цифре ошибается на каждом
    // втором десятке.
    if (11..=14).contains(&(n % 100)) {
        return many;
    }
    match n % 10 {
        1 => one,
        2..=4 => few,
        _ => many,
    }
}

/// Время работы системы словами: «3 дня 4 часа».
///
/// Не `human_duration`: та печатает `ч:мм:сс` и годится для ролика, а машина
/// работает днями — «172:04:11» человек не прочитает. Показываем две старшие
/// единицы: с точностью до секунды аптайм никому не нужен, а строка от неё
/// растёт и перестаёт влезать в карточку.
pub fn human_uptime(secs: u64) -> String {
    let (d, h, m) = (secs / 86_400, (secs % 86_400) / 3600, (secs % 3600) / 60);

    if d > 0 {
        let days = format!("{d} {}", plural_ru(d, "день", "дня", "дней"));
        if h == 0 {
            return days;
        }
        return format!("{days} {h} {}", plural_ru(h, "час", "часа", "часов"));
    }
    if h > 0 {
        let hours = format!("{h} {}", plural_ru(h, "час", "часа", "часов"));
        if m == 0 {
            return hours;
        }
        return format!("{hours} {m} {}", plural_ru(m, "минута", "минуты", "минут"));
    }
    // Меньше часа — минуты, и «0 минут» здесь законно: машину только что
    // включили.
    format!("{m} {}", plural_ru(m, "минута", "минуты", "минут"))
}

/// Частота процессора. `None` при нуле.
///
/// Ноль отсюда не выпускаем наружу значением: `sysinfo` кладёт его и когда
/// частоту не спрашивали, и когда система не ответила
/// (`CallNtPowerInformation` на Windows заполняет вектор нулями), а «0 МГц»
/// в окне читается как остановившийся процессор. Отличить два случая
/// нельзя — значит, оба «нет данных».
pub fn human_mhz(mhz: u64) -> Option<String> {
    if mhz == 0 {
        return None;
    }
    if mhz >= 1000 {
        Some(format!("{:.2} ГГц", mhz as f64 / 1000.0))
    } else {
        Some(format!("{mhz} МГц"))
    }
}

/// Проценты с округлением до целого. `None`, если число не конечное.
///
/// Проверка на конечность обязательна: `state_of_health` у батареи считается
/// делением `energy_full / energy_full_design`, и при нулевой проектной
/// ёмкости (драйвер её не сообщил) выходит `0.0 / 0.0` = `NaN`. Крейт зажимает
/// результат в диапазон, но `f32::clamp` на `NaN` возвращает `NaN`, так что
/// без этой строки в окне появилось бы «NaN %».
pub fn human_percent(value: f32) -> Option<String> {
    value.is_finite().then(|| format!("{}%", value.round() as i64))
}

/// Версия USB из двоично-десятичного поля дескриптора: `0x0200` → «2.0».
///
/// Старший байт берём как есть: у USB он не выходит за 3, и разбирать его
/// как две двоично-десятичные цифры незачем.
pub fn usb_version(bcd: u16) -> String {
    let (major, minor, sub) = (bcd >> 8, (bcd >> 4) & 0xF, bcd & 0xF);
    if sub == 0 {
        format!("{major}.{minor}")
    } else {
        format!("{major}.{minor}.{sub}")
    }
}

