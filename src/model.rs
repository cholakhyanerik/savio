//! Доменные типы. Ничего не знают ни про UI, ни про yt-dlp.

use std::path::PathBuf;

/// Что именно скачиваем.
#[derive(Clone, Copy, PartialEq, Eq, Debug, Default)]
pub enum Format {
    /// Видео со звуком, максимум в пределах MP4-контейнера. Значение по
    /// умолчанию: с ним Savio открывался всегда, и запомненные настройки
    /// откатываются именно к нему.
    #[default]
    Mp4,
    /// Только аудиодорожка, перекодированная в MP3.
    Mp3,
}

impl Format {
    pub fn label(self) -> &'static str {
        match self {
            Format::Mp4 => "MP4 — видео",
            Format::Mp3 => "MP3 — аудио",
        }
    }

    /// Имя формата без пояснения — для тесных мест.
    ///
    /// Нужно строке очереди: там рядом уже стоят ступень качества и название
    /// ролика, а ширина у окна бывает 520. «MP4 — видео» съело бы там половину
    /// строки, и от названия ролика — того единственного, по чему элемент
    /// очереди узнают, — не осталось бы ничего.
    pub fn short(self) -> &'static str {
        match self {
            Format::Mp4 => "MP4",
            Format::Mp3 => "MP3",
        }
    }

    /// Подпись поля над переключателем качества.
    ///
    /// Ступени качества у видео и звука общие, а единицы у них разные, и
    /// назвать единицу можно только здесь: на самом сегменте для неё места
    /// нет — их шесть, и в окне шириной 520 каждому достаётся около 70 точек.
    pub fn quality_label(self) -> &'static str {
        match self {
            Format::Mp4 => "Качество",
            Format::Mp3 => "Битрейт, кбит/с",
        }
    }
}

/// Насколько тяжёлый файл берём.
///
/// Отдельный тип рядом с `Format`, а не новые варианты внутри него: формат и
/// качество выбираются независимо, и внутри `Format` их пришлось бы
/// перечислять всеми комбинациями сразу — двенадцатью вместо двух и шести.
///
/// Шкала одна на оба формата, а единица у неё своя: у видео это высота кадра,
/// у звука — битрейт. Ступени идут строго сверху вниз, поэтому переключение
/// MP4 ↔ MP3 не сбивает выбранное положение в списке.
#[derive(Clone, Copy, PartialEq, Eq, Debug, Default)]
pub enum Quality {
    /// Максимум, который отдаёт источник, — ровно то, что Savio делал до
    /// появления выбора. Значение по умолчанию: старое поведение обязано
    /// остаться поведением по умолчанию.
    #[default]
    Best,
    P2160,
    P1440,
    P1080,
    P720,
    P480,
}

impl Quality {
    /// Все ступени сверху вниз — в этом порядке их и рисует переключатель.
    pub const ALL: [Quality; 6] = [
        Quality::Best,
        Quality::P2160,
        Quality::P1440,
        Quality::P1080,
        Quality::P720,
        Quality::P480,
    ];

    /// Потолок высоты кадра. `None` у `Best` — ограничения нет.
    ///
    /// Именно потолок, а не точное значение: у ролика может не быть дорожки
    /// ровно этой высоты, и требовать её означало бы отказать в загрузке.
    pub fn max_height(self) -> Option<u32> {
        match self {
            Quality::Best => None,
            Quality::P2160 => Some(2160),
            Quality::P1440 => Some(1440),
            Quality::P1080 => Some(1080),
            Quality::P720 => Some(720),
            Quality::P480 => Some(480),
        }
    }

    /// Битрейт звука в том виде, в каком его понимает `--audio-quality`.
    ///
    /// `None` у `Best`: там значение другого рода — не битрейт, а верх шкалы
    /// VBR, и подставляет его движок. Смешивать их в одном типе нельзя,
    /// иначе «0» из шкалы VBR однажды уедет в аргумент как «0 кбит/с».
    pub fn audio_bitrate(self) -> Option<&'static str> {
        match self {
            Quality::Best => None,
            Quality::P2160 => Some("320K"),
            Quality::P1440 => Some("256K"),
            Quality::P1080 => Some("192K"),
            Quality::P720 => Some("128K"),
            Quality::P480 => Some("96K"),
        }
    }

    /// Подпись на сегменте. Зависит от формата: одна и та же ступень у видео
    /// значит высоту кадра, у звука — килобиты в секунду.
    ///
    /// Подписи короткие намеренно: шесть сегментов делят ширину окна, а окно
    /// бывает шириной 520 — «Максимум» и «320 кбит/с» распёрли бы дорожку
    /// шире окна. Единицу называет `Format::quality_label` над переключателем.
    pub fn label(self, format: Format) -> &'static str {
        match format {
            Format::Mp4 => match self {
                Quality::Best => "Макс.",
                Quality::P2160 => "2160p",
                Quality::P1440 => "1440p",
                Quality::P1080 => "1080p",
                Quality::P720 => "720p",
                Quality::P480 => "480p",
            },
            Format::Mp3 => match self {
                Quality::Best => "Макс.",
                Quality::P2160 => "320",
                Quality::P1440 => "256",
                Quality::P1080 => "192",
                Quality::P720 => "128",
                Quality::P480 => "96",
            },
        }
    }

    /// Ступень вместе с единицей — там, где подписи поля рядом нет.
    ///
    /// На переключателе единицу называет `Format::quality_label` над ним,
    /// и подписи сегментов держат голыми намеренно: их шесть в ряд. А в
    /// строке очереди никакого заголовка нет, и «MP3 · 320» приходится
    /// читать как загадку — 320 чего.
    ///
    /// Возвращает статическую строку, а не собирает её: строки очереди
    /// пересобираются на каждое изменение состояния, и аллокация ради
    /// пяти символов там ни к чему.
    pub fn label_with_unit(self, format: Format) -> &'static str {
        match format {
            // У видео единица уже внутри подписи: «1080p».
            Format::Mp4 => self.label(format),
            Format::Mp3 => match self {
                Quality::Best => "Макс.",
                Quality::P2160 => "320 кбит/с",
                Quality::P1440 => "256 кбит/с",
                Quality::P1080 => "192 кбит/с",
                Quality::P720 => "128 кбит/с",
                Quality::P480 => "96 кбит/с",
            },
        }
    }
}

/// Что за локальный файл выбрал пользователь во вкладке «Метаданные».
///
/// Определяется по расширению, а не по содержимому: пользователь выбирает файл
/// сам, и наша задача — не угадать формат вопреки имени, а честно сказать, с чем
/// мы работать умеем. Настоящую проверку сигнатуры делает уже разборщик:
/// `.jpg` с PNG внутри отвергнет он, а не эта функция.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum MetaKind {
    Mp3,
    Jpeg,
    Png,
    WebP,
    Gif,
    /// Читать умеем (EXIF лежит на виду), а чистить — нет: метаданные TIFF
    /// это и есть его структура каталогов, и вычистить их можно только
    /// пересобрав файл целиком с пересчётом всех смещений на дорожки данных.
    /// Испортить снимок здесь куда легче, чем вычистить, поэтому честное
    /// «не умею» лучше молчаливой порчи.
    Tiff,
    /// Видео — вне области действия инструмента.
    Video,
    Unsupported,
}

impl MetaKind {
    /// Можно ли у этого файла прочитать метаданные.
    pub fn readable(self) -> bool {
        !matches!(self, MetaKind::Video | MetaKind::Unsupported)
    }

    /// Можно ли у этого файла удалить метаданные.
    pub fn cleanable(self) -> bool {
        self.readable() && !matches!(self, MetaKind::Tiff)
    }
}

/// Определяет тип файла по расширению.
pub fn meta_kind(path: &std::path::Path) -> MetaKind {
    let Some(ext) = path.extension().and_then(|e| e.to_str()) else {
        return MetaKind::Unsupported;
    };
    // Регистр в расширении произвольный: «IMG_0001.JPG» с телефона — обычное дело.
    let ext = ext.to_ascii_lowercase();

    match ext.as_str() {
        "mp3" => MetaKind::Mp3,
        "jpg" | "jpeg" | "jpe" | "jfif" => MetaKind::Jpeg,
        "png" | "apng" => MetaKind::Png,
        "webp" => MetaKind::WebP,
        "gif" => MetaKind::Gif,
        "tif" | "tiff" => MetaKind::Tiff,
        // Видео перечисляем явно, чтобы отличить «не поддерживаем пока»
        // от «вообще не знаем, что это»: сообщения у них разные.
        "mp4" | "m4v" | "mkv" | "avi" | "mov" | "webm" | "wmv" | "flv" | "mpg" | "mpeg"
        | "m2ts" | "ts" | "3gp" | "ogv" => MetaKind::Video,
        _ => MetaKind::Unsupported,
    }
}

/// Одна строка в списке метаданных: имя и значение, уже готовые к показу.
///
/// Значение — всегда строка: EXIF-рациональные, GPS-координаты и ID3-теги
/// приводятся к человекочитаемому виду там, где их разбирают. UI ничего
/// не форматирует и не пересобирает в кадре.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Tag {
    pub name: String,
    pub value: String,
}

impl Tag {
    pub fn new(name: impl Into<String>, value: impl Into<String>) -> Self {
        Self {
            name: name.into(),
            value: value.into(),
        }
    }
}

/// Откуда взять cookies для роликов, которые без входа в аккаунт не отдаются.
///
/// Перечисление, а не строка из поля ввода: значение уходит прямо в аргумент
/// `--cookies-from-browser`, и список имён, которые yt-dlp понимает, закрытый.
/// Со свободным вводом опечатка оборачивалась бы английской руганью вместо
/// выбора из того, что заведомо работает.
///
/// Safari в списке нет, хотя yt-dlp его знает, и это не забывчивость. На
/// Windows и Linux он отвечает `unsupported platform` (проверено вживую,
/// yt-dlp 2026.07.04), а на macOS база cookies лежит под защитой системы и
/// читается только приложением с «Полным доступом к диску» — у неподписанного
/// Savio его нет. Пункт, который заведомо не сработает, хуже отсутствующего.
///
/// Перечисление осталось `Copy`, хотя у файла есть путь: путь лежит
/// **отдельным полем** [`Request::cookie_file`]. `PathBuf` внутри варианта
/// лишил бы `Copy` тип, который сравнивают и копируют на каждой правке поля
/// ссылки (цель предпросмотра), и заодно сделал бы невозможной константу
/// [`CookieSource::ALL`], из которой рисуется список.
#[derive(Clone, Copy, PartialEq, Eq, Debug, Default)]
pub enum CookieSource {
    /// Не передавать cookies вовсе — ровно то, что Savio делал до появления
    /// этого выбора. Значение по умолчанию и единственное безопасное: читать
    /// чужой профиль браузера мы начинаем только по прямой просьбе.
    #[default]
    None,
    Chrome,
    Edge,
    Firefox,
    Opera,
    Brave,
    Vivaldi,
    Chromium,
    /// Готовый файл cookies в формате Netscape — ключ `--cookies`.
    ///
    /// Не роскошь, а единственный работающий вход для половины списка выше:
    /// Chrome и всё, что на нём основано (Edge, Brave, Opera, Vivaldi), в
    /// свежих версиях шифрует cookies через DPAPI так, что снаружи их не
    /// прочитать (проверено вживую 2026-07-27). Изнутри браузера шифрования
    /// уже нет, и расширение вроде «Get cookies.txt» выгружает те же самые
    /// cookies в текстовый файл.
    File,
}

impl CookieSource {
    /// Все источники в том порядке, в каком их рисует выпадающий список.
    ///
    /// «Не использовать» первым: это и значение по умолчанию, и то, к чему
    /// возвращаются, когда cookies сделали хуже (см. `explain_failure`).
    /// Файл последним: он требует ещё и выбрать файл, то есть стоит дороже
    /// любого пункта над ним.
    pub const ALL: [CookieSource; 9] = [
        CookieSource::None,
        CookieSource::Chrome,
        CookieSource::Edge,
        CookieSource::Firefox,
        CookieSource::Opera,
        CookieSource::Brave,
        CookieSource::Vivaldi,
        CookieSource::Chromium,
        CookieSource::File,
    ];

    /// Имя браузера в том виде, в каком его понимает `--cookies-from-browser`.
    ///
    /// `None` — браузер не при чём: либо cookies не нужны вовсе, либо их
    /// берут из файла. Спрашивать этим «просят ли вход» нельзя, для этого
    /// есть [`CookieSource::any`].
    ///
    /// Имена строчные и без пробелов: yt-dlp сверяет их со своим списком
    /// дословно и на любое другое написание отвечает отказом.
    pub fn browser(self) -> Option<&'static str> {
        match self {
            CookieSource::None | CookieSource::File => Option::None,
            CookieSource::Chrome => Some("chrome"),
            CookieSource::Edge => Some("edge"),
            CookieSource::Firefox => Some("firefox"),
            CookieSource::Opera => Some("opera"),
            CookieSource::Brave => Some("brave"),
            CookieSource::Vivaldi => Some("vivaldi"),
            CookieSource::Chromium => Some("chromium"),
        }
    }

    /// Просят ли вход на сайт хоть каким-нибудь способом.
    ///
    /// Отдельно от `browser()`, и это не удобство. До появления файла
    /// «вход просят» и «выбран браузер» значили одно и то же, и вопрос
    /// задавался через `browser().is_some()` — в сводке тонких настроек,
    /// в оговорке под списком и, что важнее всего, в `explain_failure`,
    /// где на этом держится подсказка про пустой список дорожек у YouTube.
    /// С файлом такой вопрос отвечает «вход не просят» на просьбу войти,
    /// то есть молча гасит подсказку ровно там, где она нужна.
    pub fn any(self) -> bool {
        !matches!(self, CookieSource::None)
    }

    /// Подпись в списке. Полные имена, а не токены yt-dlp: в списке человек
    /// ищет свой браузер глазами, и «Mozilla Firefox» узнаётся быстрее, чем
    /// «firefox».
    pub fn label(self) -> &'static str {
        match self {
            CookieSource::None => "Не использовать",
            CookieSource::Chrome => "Google Chrome",
            CookieSource::Edge => "Microsoft Edge",
            CookieSource::Firefox => "Mozilla Firefox",
            CookieSource::Opera => "Opera",
            CookieSource::Brave => "Brave",
            CookieSource::Vivaldi => "Vivaldi",
            CookieSource::Chromium => "Chromium",
            // С многоточием, как принято у пунктов, открывающих диалог:
            // выбрать этот пункт мало, следом придётся назвать файл.
            CookieSource::File => "Из файла…",
        }
    }
}

/// Что дополнительно вшить в готовый файл.
///
/// Плоская структура из флажков, а не варианты перечисления: галочки
/// независимы, и любая их комбинация осмысленна. Значение по умолчанию —
/// все выключены, то есть ровно то, что Savio делал до появления опций.
///
/// Вшивание целиком лежит на `ffmpeg`, и это не деталь реализации, а свойство,
/// от которого зависит поведение: без него запрошенное вшивание не просто
/// не сработает, а **уронит всю загрузку** (подробности — в `download_args`).
/// Отсюда `any()`: спрашивать про ffmpeg надо один раз на все флажки.
#[derive(Clone, Copy, PartialEq, Eq, Debug, Default)]
pub struct DownloadOptions {
    pub embed_metadata: bool,
    pub embed_thumbnail: bool,
    pub embed_subs: bool,
    /// Годятся ли автоматические субтитры — распознавание речи и машинный
    /// перевод с него.
    ///
    /// Не самостоятельная просьба, а уточнение к `embed_subs`: без неё
    /// вшивать нечего, и в командной строке ключ появляется только рядом
    /// с `--embed-subs`. Отсюда же то, что `any()` этот флажок **не**
    /// считает: `any()` отвечает на вопрос «нужен ли ffmpeg», и одинокая
    /// галочка «можно автоматические» ответила бы на него «да» там, где
    /// вшивать не просят вовсе, — человек получил бы предупреждение
    /// про ненайденный ffmpeg на пустом месте.
    ///
    /// Отдельная галочка, а не молчаливое расширение `embed_subs`, потому
    /// что качество у распознанных субтитров заметно хуже авторских:
    /// включать такое за человека нельзя.
    pub auto_subs: bool,
}

impl DownloadOptions {
    /// Просят ли вшить хоть что-нибудь.
    pub fn any(self) -> bool {
        self.embed_metadata || self.embed_thumbnail || self.embed_subs
    }
}

/// На каком языке нужны субтитры.
///
/// Перечисление с кодом внутри, а не голая строка: «язык ролика» — это не
/// код, а просьба определить его по ответу `probe`, и представить её пустой
/// строкой значило бы смешать «не выбрано» с «выбрано ничего».
///
/// Значение по умолчанию — `Original`, и это не вкусовщина. Без явного
/// `--sub-langs` yt-dlp берёт `en`, а YouTube кладёт в автоматические
/// субтитры машинный перевод на сотню языков, и `en` среди них есть почти
/// всегда: в русский ролик вшился бы английский перевод русского же
/// распознавания. Проверено вживую (yt-dlp 2026.07.04) — см. `download_args`.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub enum SubLang {
    /// Тот язык, на котором ролик снят. Определяется по ответу `probe`
    /// (`MediaInfo::subtitle_code`), а не угадывается в UI.
    #[default]
    Original,
    /// Выбранный человеком код языка — ровно в том виде, в каком его
    /// понимает `--sub-langs`.
    Code(String),
}

impl SubLang {
    /// Подпись первого пункта списка. Здесь же, а не в UI, потому что
    /// её называет и объяснение про недоступный язык.
    pub const ORIGINAL_LABEL: &'static str = "Язык ролика";
}

/// Что решено про субтитры этой загрузки.
///
/// Собирается после `probe` (`MediaInfo::subtitle_plan`) и уезжает прямо
/// в аргументы: до ответа сайта ни языка, ни выбора между автором и роботом
/// не существует.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct SubtitlePlan {
    /// Код языка для `--sub-langs`. `None` — определить не вышло, и ключа
    /// в командной строке не будет вовсе.
    pub lang: Option<String>,
    /// Просить ли у yt-dlp автоматические субтитры.
    ///
    /// Это **не** галочка «Можно автоматические», и разница не косметическая.
    /// Проверено вживую (yt-dlp 2026.07.04) на ролике, у которого есть и
    /// авторские субтитры, и распознанные: с `--embed-subs --write-auto-subs
    /// --sub-langs en` в файл уехали **распознанные**, хотя авторские на том
    /// же языке лежали рядом. Ни ошибки, ни предупреждения — код возврата 0,
    /// подмену видно только по тексту субтитров («[Music]» вместо «[♪♪♪]»).
    /// Убери `--write-auto-subs` — вшиваются авторские.
    ///
    /// Поэтому приоритет держит Savio, а не yt-dlp: робота зовём только туда,
    /// где автора нет. Галочка при этом значит ровно то, что на ней написано:
    /// «можно и робота», а не «robotа вместо автора».
    pub auto: bool,
}

impl SubtitlePlan {
    /// План на случай, когда про ролик не известно ничего: `probe` не прошёл.
    ///
    /// Языка нет — ключа не будет, и yt-dlp возьмёт своё умолчание, ровно
    /// как до появления выбора языка. Галочку при этом уважаем: «нет данных,
    /// значит и не пытаемся» молча выключило бы возможность.
    pub fn blind(allow_auto: bool) -> Self {
        Self {
            lang: None,
            auto: allow_auto,
        }
    }
}

/// Одна дорожка субтитров, которую предлагает источник.
///
/// `label` собран заранее, в движке: список у YouTube доходит до полутора
/// сотен языков, и склеивать подписи в кадре отрисовки нельзя (Правило 1).
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct SubtitleTrack {
    /// Код языка в том виде, в каком его понимает `--sub-langs`: «ru»,
    /// «pt-BR», а иногда и «en-nP7-2PuUl7o» — YouTube так называет вторую
    /// английскую дорожку одного ролика.
    pub code: String,
    /// Что показать в списке: имя языка от источника плюс сам код.
    pub label: String,
    /// Автоматические: распознавание речи или машинный перевод с него.
    ///
    /// Разделять обязательно. Авторские субтитры выкладывает человек, и
    /// они точные; автоматические пишет робот, и вшивать их без спроса
    /// нельзя. Плюс на этом держится приоритет: при одинаковом коде
    /// в списке остаётся авторская дорожка.
    pub auto: bool,
}

/// Фрагмент ролика: с какой секунды по какую его вырезать.
///
/// Обе границы независимы и обе необязательны: «с 1:30 и до конца» и «с начала
/// по 4:00» — такие же законные просьбы, как полный диапазон. Обе пустые
/// значат «скачать целиком» — ровно то, что Savio делал до появления обрезки,
/// и потому это значение по умолчанию.
///
/// Секунды, а не набранные строки: разбор — работа домена, и до движка должно
/// доезжать уже проверенное число. Строка «4:00» в аргументе `yt-dlp` была бы
/// не ошибкой, а тихой бедой (см. `section_arg`).
#[derive(Clone, Copy, PartialEq, Eq, Debug, Default)]
pub struct Section {
    pub start: Option<u64>,
    pub end: Option<u64>,
}

impl Section {
    /// Просят ли вырезать фрагмент.
    ///
    /// Нужна по той же причине, что и `DownloadOptions::any()`: обрезка целиком
    /// лежит на ffmpeg, и спросить «а есть ли он» надо один раз на обе границы.
    pub fn any(self) -> bool {
        self.start.is_some() || self.end.is_some()
    }

    /// Доля ролика, начиная с которой выгоднее скачать целиком и вырезать самим.
    ///
    /// Половина выбрана не по замерам времени, и это важно понимать, прежде
    /// чем её двигать. По одному только секундомеру порог вышел бы куда ниже:
    /// целый ролик из замеров ниже качается за то же время, что кусок в
    /// **восьмую** его часть, — то есть быстрым путём стоило бы брать уже
    /// восьмую. Но время не единственная цена. Быстрый путь тянет из сети
    /// весь ролик и держит его на диске, пока идёт обрезка, а просили кусок:
    /// на половине переплата ограничена **двойным** трафиком и двойным
    /// местом, на восьмой была бы восьмикратной. Отсюда и правило: порог
    /// стоит там, где переплата ещё соразмерна просьбе, а не там, где
    /// секундомер впервые показал выигрыш.
    ///
    /// Двигать его вниз — значит качать целые ролики ради минутных кусков
    /// (и на дорогом мобильном тарифе это хуже долгого ожидания); вверх —
    /// терять ровно тот случай, ради которого всё затевалось.
    const CUT_AFTER_SHARE: f64 = 0.5;

    /// Каким путём брать этот фрагмент, зная длительность ролика.
    ///
    /// `duration` — то, что ответил `probe`; `None` значит «не знаем».
    /// Тогда путь прежний, медленный: гадать о доле, не зная целого, нельзя,
    /// а скачать двухчасовую запись ради десяти секунд — цена ошибки,
    /// которой не хочется.
    ///
    /// Замерено на одном ролике и одних дорожках (Big Buck Bunny, 480p,
    /// yt-dlp 2026.08.19, 2026-08-21). Ролик длится 10:35 и целиком весит
    /// 34,8 МБ; качается целиком за 11,6 с, своя обрезка добавляет к этому
    /// от 0,1 до 0,3 с независимо от длины куска:
    ///
    /// | кусок | `--download-sections` | целиком + своя обрезка |
    /// |---|---|---|
    /// | 30 с   | 6–23 с | 11,8 с |
    /// | 2 мин  | 69 с   | 11,8 с |
    /// | 5 мин  | 176 с  | 11,9 с |
    ///
    /// Разница не в самой обрезке, а в том, кто качает: при
    /// `--download-sections` это запущенный yt-dlp ffmpeg, одним
    /// последовательным потоком со скоростью 80–190 КБ/с против 3,0 МБ/с
    /// у обычной загрузки. То есть медленный путь проигрывает **на байт**
    /// в 16–38 раз, и чем длиннее кусок, тем больше набегает.
    ///
    /// Куски из таблицы вырезаны обоими путями и сверены: длительность
    /// совпала до микросекунды (30,000544 / 120,001088 / 300,002177 с).
    /// Свой путь отдаёт тот же фрагмент, а не похожий.
    pub fn plan(self, duration: Option<f64>) -> SectionPlan {
        if !self.any() {
            return SectionPlan::Whole;
        }

        // Длительность бывает нулевой и бесконечной: у трансляции её нет
        // вовсе, а `as_f64` отдаёт что придёт. Делить на такое нельзя.
        let Some(duration) = duration.filter(|secs| secs.is_finite() && *secs > 0.0) else {
            return SectionPlan::Stream;
        };

        // Открытый конец — это «до конца ролика», а конец за концом ролика
        // ролик не удлиняет: и то и другое упирается в `duration`.
        let start = self.start.unwrap_or(0) as f64;
        let end = self.end.map_or(duration, |end| end as f64).min(duration);
        let length = (end - start).max(0.0);

        if length >= duration * Self::CUT_AFTER_SHARE {
            SectionPlan::CutAfter
        } else {
            SectionPlan::Stream
        }
    }
}

/// Каким путём добывать запрошенный фрагмент.
///
/// Вариантов три, а не два, потому что «фрагмента не просят» и «фрагмент
/// просят, но резать будем сами» — это разные командные строки и разный
/// набор стадий, и свести их не к чему.
///
/// Названы варианты по действию, а не по причине, намеренно: `Whole` достаётся
/// и тому, кто фрагмента не просил, и тому, у кого нет ffmpeg, — делаем в
/// обоих случаях ровно одно и то же.
///
/// Считается это до запуска и один раз, [`Section::plan`]; в кадре отрисовки
/// и в цикле разбора вывода решать нечего.
#[derive(Clone, Copy, PartialEq, Eq, Debug, Default)]
pub enum SectionPlan {
    /// Качать целиком и ничего не резать.
    #[default]
    Whole,
    /// Просить кусок у самого yt-dlp — ключ `--download-sections`.
    ///
    /// Качает при этом не yt-dlp, а запущенный им ffmpeg, одним
    /// последовательным потоком: процентов не будет, а скорость на байт
    /// в разы ниже обычной.
    Stream,
    /// Скачать ролик целиком обычным быстрым путём и вырезать кусок своим
    /// вызовом ffmpeg уже на диске.
    CutAfter,
}

/// Почему набранный фрагмент не годится.
///
/// Перечисление, а не готовая строка: под полями показывают текст, а красной
/// рамкой — конкретное поле, и знать, какое именно, можно только отсюда.
/// И оно `Copy`: значение живёт в поле экрана, а собирать `String` на каждое
/// нажатие клавиши незачем.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum SectionError {
    /// Начало не разобралось.
    Start,
    /// Конец не разобрался.
    End,
    /// Конец не позже начала — вырезать нечего.
    Order,
}

impl SectionError {
    /// Что показать под полями.
    pub fn message(self) -> &'static str {
        match self {
            SectionError::Start => {
                "Начало не похоже на время. Нужно «1:30», «1:02:03» или число секунд."
            }
            SectionError::End => {
                "Конец не похож на время. Нужно «4:00», «1:02:03» или число секунд."
            }
            SectionError::Order => "Конец должен быть позже начала.",
        }
    }

    /// Подсвечивать ли поле начала.
    pub fn at_start(self) -> bool {
        matches!(self, SectionError::Start | SectionError::Order)
    }

    /// Подсвечивать ли поле конца. Перевёрнутый диапазон — беда обоих полей
    /// сразу: какое из двух чисел человек имел в виду поправить, мы не знаем.
    pub fn at_end(self) -> bool {
        matches!(self, SectionError::End | SectionError::Order)
    }
}

/// Разбирает «1:30», «1:02:03» или «90» в секунды — обратная к `human_duration`.
///
/// Принимает от одного до трёх полей через двоеточие: секунды, «минуты:секунды»
/// и «часы:минуты:секунды». Всё остальное — `None`. Вытащить из строки первое
/// попавшееся число было бы хуже честного отказа: человек получил бы не тот
/// кусок ролика и узнал бы об этом, только открыв файл.
///
/// Поля после первого ограничены шестьюдесятью: «1:75» — это либо опечатка,
/// либо «минута и 75 секунд», и угадывать, что имелось в виду, не наше дело.
/// У первого поля потолка нет: «90» — законные полторы минуты, а «120:00» —
/// два часа.
pub fn parse_timecode(text: &str) -> Option<u64> {
    let text = text.trim();
    if text.is_empty() {
        return None;
    }

    let mut secs: u64 = 0;
    let mut fields = 0;
    for field in text.split(':') {
        fields += 1;
        if fields > 3 {
            return None;
        }

        // Проверяем цифры сами, а не полагаемся на `parse`: он принимает
        // ведущий плюс, и «+5» стало бы законным временем.
        let field = field.trim();
        if field.is_empty() || !field.bytes().all(|b| b.is_ascii_digit()) {
            return None;
        }
        let value: u64 = field.parse().ok()?;
        if fields > 1 && value > 59 {
            return None;
        }

        // `checked_*`, а не `*`: строка приходит из поля ввода, и «999999999999»
        // в часах — это переполнение, то есть паника в отладочной сборке
        // и тихо неверное число в выпускной.
        secs = secs.checked_mul(60)?.checked_add(value)?;
    }

    Some(secs)
}

/// Собирает фрагмент из того, что человек набрал в двух полях.
///
/// Пустое поле — не ошибка, а «границы нет»: оба пустых дают `Section` по
/// умолчанию, то есть загрузку целиком.
///
/// Проверка порядка живёт здесь, до запуска, и это не перестраховка:
/// перевёрнутый диапазон yt-dlp ошибкой не считает — он выходит с кодом 0
/// и отдаёт файл, в котором лежит не то, что просили.
pub fn parse_section(start: &str, end: &str) -> Result<Section, SectionError> {
    let start = parse_bound(start).ok_or(SectionError::Start)?;
    let end = parse_bound(end).ok_or(SectionError::End)?;

    // Пустое начало — это ноль, и сравнивать с ним надо тоже: «до 0:00» —
    // такой же пустой фрагмент, как «с 4:00 по 1:30».
    if let Some(end) = end
        && end <= start.unwrap_or(0)
    {
        return Err(SectionError::Order);
    }

    // «0:00» в поле начала — это и есть начало ролика. Держать его отдельной
    // границей незачем: с ней `any()` отвечал бы «фрагмент просят» на просьбу
    // скачать всё, и целый ролик поехал бы медленным путём обрезки.
    let start = start.filter(|&secs| secs > 0);

    Ok(Section { start, end })
}

/// Одна граница: пусто — `Some(None)`, время — `Some(Some(секунды))`,
/// мусор — `None`. Три исхода, и различать их обязательно: пустое поле
/// и опечатка в нём значат противоположное.
fn parse_bound(text: &str) -> Option<Option<u64>> {
    if text.trim().is_empty() {
        return Some(None);
    }
    parse_timecode(text).map(Some)
}

/// Что именно просят скачать.
///
/// Отдельная структура, а не тройка параметров: формат и качество ходят
/// вместе через движок, поток и сборку аргументов, и каждый новый признак
/// загрузки удлинял бы там четыре сигнатуры разом.
#[derive(Clone, Debug)]
pub struct Request {
    pub url: String,
    pub format: Format,
    pub quality: Quality,
    pub options: DownloadOptions,
    /// Какой кусок ролика нужен. Пустой `Section` — весь целиком.
    ///
    /// Поле запроса, а не флажок внутри `DownloadOptions`: там собрано то,
    /// что вшивается в готовый файл, и на `any()` этой структуры держится
    /// единственная проверка «нужен ли ffmpeg» для вшивания. Обрезке ffmpeg
    /// нужен тоже, но по своей причине и с другим исходом при его нехватке,
    /// так что и спрашивать про неё надо отдельно.
    pub section: Section,
    /// Откуда взять вход в аккаунт. Поле запроса, а не четвёртый флажок внутри
    /// `DownloadOptions`: там собрано то, что вшивается в готовый файл, и
    /// держится на этом `any()` — единственная проверка «нужен ли ffmpeg».
    /// Cookies к ffmpeg отношения не имеют, и попади они в ту же структуру,
    /// первый же, кто честно допишет их в `any()`, начнёт ругаться на
    /// отсутствие ffmpeg там, где он не нужен.
    pub cookies: CookieSource,
    /// Путь к файлу cookies. Значит что-нибудь только при
    /// [`CookieSource::File`], в остальных случаях не смотрится.
    ///
    /// Отдельным полем, а не путём внутри варианта перечисления: `PathBuf`
    /// там лишил бы [`CookieSource`] `Copy` (подробности — в его описании).
    /// `None` при `File` — файл ещё не выбран; ключа в командной строке
    /// тогда нет вовсе, а движок про это предупреждает.
    pub cookie_file: Option<PathBuf>,
    /// Язык субтитров. Поле запроса, а не флажок внутри `DownloadOptions`:
    /// там всё `Copy`, а язык — строка, и одна её строчка лишила бы
    /// `Copy` структуру, которую копируют в каждом кадре.
    pub sub_lang: SubLang,
}

/// Метаданные ролика, полученные до начала загрузки.
#[derive(Clone, Debug, Default)]
pub struct MediaInfo {
    pub title: Option<String>,
    pub uploader: Option<String>,
    pub duration_secs: Option<f64>,
    /// Высоты кадра, которые источник действительно отдаёт: по убыванию, без
    /// повторов. Пусто — либо видеодорожек нет вовсе, либо экстрактор их
    /// не перечислил; и то и другое законно, показывать тогда просто нечего.
    pub heights: Vec<u32>,
    /// Адрес обложки, если экстрактор её назвал. Сама картинка приезжает
    /// отдельным событием: `-J` отдаёт только ссылку, а тянуть по ней байты —
    /// это ещё один запрос в сеть.
    pub thumbnail_url: Option<String>,
    /// Язык самого ролика, как его назвал экстрактор: «ru», «en». `None` —
    /// не назвал, и это обычное дело: из четырёх проверенных вживую роликов
    /// YouTube поле заполнил у двух.
    ///
    /// Нужен ровно для одного — понять, какой язык считать «языком ролика»
    /// при выборе субтитров. Угадать его иначе нечем: в автоматических
    /// субтитрах YouTube распознанный язык лежит вперемешку с машинным
    /// переводом на полторы сотни других.
    pub language: Option<String>,
    /// Дорожки субтитров, которые предлагает источник: сначала авторские,
    /// потом автоматические. Пусто — субтитров нет вовсе.
    ///
    /// Готовый список, а не голое «есть/нет», потому что язык надо выбирать:
    /// без явного `--sub-langs` yt-dlp берёт `en` (см. [`SubLang`]).
    pub subtitles: Vec<SubtitleTrack>,
}

impl MediaInfo {
    /// Самая большая доступная высота кадра.
    ///
    /// Список отсортирован по убыванию там, где собирается, — здесь только
    /// первый элемент, потому что вызывается это из кадра отрисовки.
    pub fn max_height(&self) -> Option<u32> {
        self.heights.first().copied()
    }

    /// Дорожки, из которых человеку дают выбирать.
    ///
    /// `allow_auto` — состояние галочки «можно автоматические». Показывать
    /// их, когда галочка снята, нельзя: выбранный язык просто не приехал бы,
    /// и yt-dlp сообщил бы об этом в `[info]`, который глушит `--quiet`.
    pub fn subtitle_tracks(&self, allow_auto: bool) -> impl Iterator<Item = &SubtitleTrack> {
        self.subtitles
            .iter()
            .filter(move |track| allow_auto || !track.auto)
    }

    /// Найдётся ли дорожка на этом языке среди разрешённых.
    pub fn has_subtitle(&self, code: &str, allow_auto: bool) -> bool {
        self.subtitle_tracks(allow_auto)
            .any(|track| track.code == code)
    }

    /// Подпись дорожки по коду. `None` — такой дорожки у ролика нет.
    pub fn subtitle_label(&self, code: &str) -> Option<&str> {
        self.subtitles
            .iter()
            .find(|track| track.code == code)
            .map(|track| track.label.as_str())
    }

    /// Какой код языка уедет в `--sub-langs`. `None` — определить не вышло,
    /// и тогда ключа в командной строке не будет вовсе: yt-dlp возьмёт своё
    /// умолчание, ровно как до появления выбора языка.
    ///
    /// Правила перебираются сверху вниз, и каждое проверено на живом ответе
    /// `-J`, а не выведено из документации:
    ///
    /// 1. **Язык, названный экстрактором, если такая дорожка есть.** Самый
    ///    надёжный признак: у русского ролика это `language: "ru"`, и
    ///    дорожка `ru` в автоматических — та самая распознанная (в её
    ///    адресе нет `tlang`, в отличие от переводов).
    /// 2. **Единственная авторская дорожка** — даже когда язык назван, но
    ///    дорожки на нём нет. Тот же выбор, что у хвостового `/b` в `-f`:
    ///    отдать доступное лучше, чем отказать. У ролика с `language: "ru"`
    ///    и единственными английскими субтитрами автора до появления выбора
    ///    языка вшивались именно они, и отнимать это — поломка старого
    ///    (Правило 2), а не строгость.
    /// 3. **Язык экстрактора, даже если дорожки на нём нет.** Так честнее
    ///    молчания: человек получит объяснение «субтитров на этом языке
    ///    нет», а не файл без субтитров без единого слова.
    ///
    /// Авторских дорожек несколько и языка экстрактор не назвал — выбрать
    /// не из чего, и выдумывать нельзя: `None`.
    pub fn subtitle_code<'a>(&'a self, want: &'a SubLang) -> Option<&'a str> {
        if let SubLang::Code(code) = want {
            return Some(code);
        }

        let language = self
            .language
            .as_deref()
            .filter(|language| !language.is_empty());

        if let Some(language) = language
            && self.subtitles.iter().any(|track| track.code == language)
        {
            return Some(language);
        }

        let mut own = self.subtitles.iter().filter(|track| !track.auto);
        if let (Some(only), None) = (own.next(), own.next()) {
            return Some(&only.code);
        }

        language
    }

    /// Что просить у yt-dlp: язык и нужен ли робот.
    ///
    /// `allow_auto` — состояние галочки «Можно автоматические». Робота
    /// зовём только туда, где авторской дорожки нет: при обоих ключах сразу
    /// yt-dlp вшивает именно робота, даже когда автор выложил субтитры на том
    /// же языке (проверено вживую, подробности — у [`SubtitlePlan::auto`]).
    pub fn subtitle_plan(&self, want: &SubLang, allow_auto: bool) -> SubtitlePlan {
        let lang = self.subtitle_code(want).map(str::to_owned);

        let authored = match lang.as_deref() {
            Some(code) => self
                .subtitles
                .iter()
                .any(|track| !track.auto && track.code == code),
            // Язык не определился — просим «что дадите». Авторские дорожки
            // в таком ролике есть, и отдать надо их, а не робота.
            None => self.subtitles.iter().any(|track| !track.auto),
        };

        SubtitlePlan {
            lang,
            auto: allow_auto && !authored,
        }
    }

    /// Почему запрошенных субтитров не будет — или `None`, если всё в порядке.
    ///
    /// Сказать об этом можем только мы, и в этом всё дело. Запрошенного
    /// языка у ролика нет — yt-dlp выходит **с кодом 0**, без файла
    /// субтитров и без единого слова: сообщение уходит в `[info]`, который
    /// глушит `--quiet`. Проверено вживую (yt-dlp 2026.07.04): `--sub-langs zz`
    /// не напечатал ничего. То есть галочка молча не срабатывает, и человек
    /// узнаёт об этом, только открыв готовый файл.
    ///
    /// Собирает строку, поэтому зовётся не из кадра отрисовки, а из
    /// обработчиков (`rebuild_subs_note`) — как и всё остальное в UI.
    pub fn subtitle_note(&self, want: &SubLang, allow_auto: bool) -> Option<String> {
        // Подходящих дорожек нет вовсе — язык тут ни при чём.
        if self.subtitle_tracks(allow_auto).next().is_none() {
            return Some(if self.subtitles.is_empty() {
                "Субтитров у этого ролика нет вовсе — ни своих, ни \
                 автоматических. Вшивать нечего."
                    .to_owned()
            } else {
                "Своих субтитров у этого ролика нет, зато есть автоматические. \
                 Поставьте «Можно автоматические» — только учтите, что их \
                 пишет робот и ошибки в них обычное дело."
                    .to_owned()
            });
        }

        // Язык не определился: ключа в командной строке не будет, yt-dlp
        // возьмёт своё умолчание. Что именно он возьмёт, мы не знаем, —
        // значит и говорить нечего.
        let code = self.subtitle_code(want)?;
        if self.has_subtitle(code, allow_auto) {
            return None;
        }

        let name = self.subtitle_label(code).unwrap_or(code);
        Some(format!(
            "Субтитров на этом языке ({name}) у ролика нет — файл сохранится \
             без них. Выберите другой язык из списка."
        ))
    }
}

/// Обложка ролика, уже разобранная в пиксели.
///
/// Хранится готовым RGBA, а не байтами файла, и это не мелочь: своего
/// разборщика картинок у egui нет, а декодировать JPEG в потоке отрисовки
/// нельзя — он обязан успевать 60 раз в секунду (Правило 1). Поэтому разбор
/// и уменьшение делает движок, а UI остаётся одно движение: залить готовые
/// байты в текстуру.
///
/// Размеры в `usize` не для красоты: `ColorImage::from_rgba_unmultiplied`
/// принимает `[usize; 2]`, и приведение типов пришлось бы делать в UI.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Thumbnail {
    pub width: usize,
    pub height: usize,
    /// По четыре байта на точку (R, G, B, A), слева направо и сверху вниз.
    pub rgba: Vec<u8>,
}

impl Thumbnail {
    /// Сходятся ли размеры с длиной буфера.
    ///
    /// Проверять обязательно, и вот почему: `ColorImage::from_rgba_unmultiplied`
    /// на несовпадении не возвращает ошибку, а **паникует**. Уронить приложение
    /// из-за украшения — самый обидный из возможных исходов, поэтому UI
    /// спрашивает об этом перед заливкой в текстуру, а движок — сразу после
    /// разбора. Нулевую сторону тоже не пропускаем: текстура нулевого размера
    /// egui не нужна.
    pub fn is_valid(&self) -> bool {
        self.width > 0
            && self.height > 0
            && self
                .width
                .checked_mul(self.height)
                .and_then(|pixels| pixels.checked_mul(4))
                == Some(self.rgba.len())
    }
}

/// Номер загрузки: им помечены её события.
///
/// Канал `Event` в Savio один, и это часть контракта слоёв — движок обязан
/// оставаться пригодным для CLI и тестов, поэтому второй канал под очередь
/// заводить нельзя. А загрузок в очереди много, и убитый `Handle::cancel()`
/// процесс дописывает свои события ещё какое-то время после того, как UI про
/// него забыл. Без номера такой запоздалый `Failed` пометил бы ошибкой
/// следующий элемент очереди — загрузку, с которой всё в порядке.
///
/// Номер, а не индекс в очереди: элементы из неё удаляют, и после удаления
/// индексы соседей съезжают — событие досталось бы не тому.
pub type DownloadId = u32;

/// Номер для событий, которые к загрузке отношения не имеют: установка
/// инструментов при первом запуске и работа с метаданными локального файла.
///
/// Ноль отдан под это намеренно, а загрузки нумеруются с единицы: так
/// `Progress::default()` не притворяется чужой загрузкой, а честно говорит
/// «я не из очереди».
pub const NO_DOWNLOAD: DownloadId = 0;

/// Состояние текущей загрузки.
#[derive(Clone, Copy, Debug, Default)]
pub struct Progress {
    /// Чей это прогресс. `NO_DOWNLOAD` — установки инструментов.
    ///
    /// Проставляет его движок (`engine::run`), а не разборщик строк:
    /// `parse_line` про очередь не знает и знать не должен — он остаётся
    /// чистой функцией от одной строки вывода.
    pub download_id: DownloadId,
    pub downloaded: u64,
    pub total: u64,
    pub speed_bps: Option<f64>,
    pub eta_secs: Option<u64>,
}

impl Progress {
    /// Доля выполнения, если общий размер известен.
    ///
    /// Для потоковых источников `total` приходит нулём — в этом случае
    /// показывать нечего, и UI рисует неопределённый индикатор.
    pub fn fraction(&self) -> Option<f32> {
        if self.total > 0 {
            Some((self.downloaded as f32 / self.total as f32).clamp(0.0, 1.0))
        } else {
            None
        }
    }
}

/// Что известно о версии внешней программы.
///
/// Три состояния, а не `Option<String>`, потому что «не найдена» и «найдена,
/// но версию узнать не вышло» — разные новости, и советы по ним
/// противоположные. В первом случае программу надо ставить, во втором всё уже
/// работает: просто её сборка печатает версию не так, как мы ожидали. Свести
/// их в одно `None` значило бы предлагать установку тому, у кого всё на месте.
///
/// Второе состояние — не выдуманный запас. Строку версии печатает чужая
/// программа, формат её нигде не зафиксирован, и разбор по приметам заведомо
/// может промахнуться (тот же довод, что записан у `explain_failure`).
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub enum ToolVersion {
    /// На машине не найдена.
    #[default]
    Missing,
    /// Найдена и запускается, но версию из её вывода вычитать не удалось.
    Unknown,
    /// То, что программа сама о себе напечатала.
    Known(String),
}

/// Версии внешних инструментов — для строки обслуживания.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct ToolVersions {
    pub ytdlp: ToolVersion,
    pub ffmpeg: ToolVersion,
}

/// События, которые движок отдаёт наружу. Единственный канал связи с UI.
///
/// Один и тот же набор обслуживает и загрузку ролика, и установку внешних
/// инструментов при первом запуске: обе задачи описываются одинаково —
/// стадия, прогресс, журнал, исход. Отдельный канал под установку заводить
/// не нужно, иначе движок перестал бы быть пригодным для CLI без правок.
#[derive(Clone, Debug)]
pub enum Event {
    /// Метаданные подъехали.
    Info(MediaInfo),
    /// Обложка ролика разобрана и уменьшена — можно заводить текстуру.
    ///
    /// Отдельно от `Info`, а не полем внутри него: адрес обложки приезжает
    /// вместе с метаданными, а сама картинка — отдельным запросом в сеть, и
    /// ждать её, чтобы отправить всё одним событием, значило бы задержать
    /// название ролика на время загрузки картинки. Неудача этого запроса
    /// ничего не ломает: события просто не будет (см. `engine::run`).
    Thumbnail(Thumbnail),
    /// Сменилась фаза работы — человекочитаемая строка для статус-бара.
    Stage(String),
    Progress(Progress),
    /// Строка диагностики (stderr yt-dlp, аргументы запуска и т.п.).
    Log(String),
    /// Готово, файл лежит здесь.
    ///
    /// Номер загрузки обязателен: пока это событие шло по каналу, UI мог
    /// снять её с очереди и запустить следующую. Отметить готовым не тот
    /// элемент — значит показать «Готово» рядом с чужим путём.
    Done { id: DownloadId, path: PathBuf },
    /// Не вышло, и вот почему.
    ///
    /// Один вариант на три задачи: сорвавшуюся загрузку, неудачную установку
    /// инструментов и ошибку разбора метаданных. У последних двух номер —
    /// `NO_DOWNLOAD`: они ходят по своим приёмникам, и разводить там нечего.
    Failed { id: DownloadId, message: String },
    /// Установка завершена: всё необходимое на месте, можно работать.
    /// Отдельный вариант, а не `Done`, потому что файла здесь нет —
    /// путь показывать нечего, и UI просто закрывает модалку.
    Ready,
    /// Работать можно, но с оговоркой — например, не поставился `ffmpeg`.
    ///
    /// Отдельно от `Log`: журнал свёрнут и очищается перед каждой загрузкой,
    /// поэтому предупреждение в нём пропадает ровно тогда, когда становится
    /// нужным. И отдельно от `Failed`: это не отказ, работа продолжается.
    Warning(String),
    /// Всё прошло хорошо, и об этом надо сказать словами: например, до какой
    /// версии обновился yt-dlp или что он и так был последним.
    ///
    /// Отдельно от `Ready` по той же причине, по какой `Warning` отделён от
    /// `Log`: `Ready` только закрывает модалку, и без текста рядом обновление
    /// выглядело бы как «ничего не произошло» — а именно это и надо было
    /// отличить от настоящего обновления.
    Notice(String),
    /// Метаданные локального файла прочитаны. Пустой список — законный исход
    /// («Метаданные не найдены»), а не ошибка: чистый файл выглядит именно так.
    Tags(Vec<Tag>),
    /// Метаданные удалены, файл стал легче на столько байт.
    ///
    /// Ноль здесь тоже законен: чистить было нечего, файл не тронут. Отдельно
    /// от `Notice`, потому что число надо форматировать по-человечески, а это
    /// работа UI: движок числами и оперирует.
    Cleaned(u64),
    /// Версии установленных инструментов.
    ///
    /// Отдельным событием, а не полем при запуске, потому что узнаются они
    /// запуском двух чужих программ: `yt-dlp --version` у замороженной
    /// PyInstaller-сборки отвечает не мгновенно, и спрашивать его в потоке
    /// UI нельзя (Правило 1). Приходит и после установки, и после обновления:
    /// ровно тогда версии и меняются.
    Versions(ToolVersions),
    /// Снимок системы собран целиком.
    ///
    /// Одним событием, а не пунктом за пунктом: собирается снимок за доли
    /// секунды, и показывать карточки по мере готовности значило бы устроить
    /// в окне мельтешение ради выигрыша, которого не видно. Пустого отчёта
    /// здесь не бывает — сам список пунктов не зависит от того, ответило ли
    /// железо: не ответившее приезжает пунктом со статусом «нет данных».
    SystemReport(SystemReport),
    /// Свежий замер монитора производительности.
    ///
    /// В отличие от `SystemReport`, приезжает не однажды, а каждую секунду,
    /// пока открыта вкладка или включён оверлей. Поэтому внутри уже готовые
    /// строки: собрать их шестьдесят раз в секунду ради одного изменения
    /// значило бы сделать пятьдесят девять лишних раз (Правило 1).
    Perf(PerfSample),
    /// Схемы электропитания и режим питания — прочитанные заново.
    ///
    /// Приезжает и на открытие половины «Сейчас», и после каждого
    /// переключения: по Правилу 6 применённым считается не то, что система
    /// приняла с кодом успеха, а только то, что она же и подтвердила при
    /// перечитывании. Поэтому событие с состоянием идёт **после** `Notice`
    /// или `Warning` об исходе, а не вместо него.
    Power(PowerState),
}

/// Похожа ли строка на ссылку, которую есть смысл отдавать yt-dlp.
///
/// Проверка намеренно грубая: её задача — поймать очевидную опечатку
/// (забытый протокол, случайный текст из буфера обмена), а не отфильтровать
/// всё неверное. Список поддерживаемых сайтов знает yt-dlp, а не Savio,
/// поэтому UI только подсвечивает поле и **не** блокирует кнопку: решение
/// всегда остаётся за пользователем.
pub fn looks_like_url(text: &str) -> bool {
    let text = text.trim();
    let Some(rest) = text
        .strip_prefix("https://")
        .or_else(|| text.strip_prefix("http://"))
    else {
        return false;
    };

    // Хост — всё до первого разделителя пути. Он обязан существовать и
    // содержать точку: «https://» и «https://youtube» ссылками ещё не являются.
    let host = rest
        .split(['/', '?', '#'])
        .next()
        .unwrap_or_default()
        .trim();

    host.contains('.') && !host.starts_with('.') && !host.ends_with('.') && !host.contains(' ')
}

/// Единицы объёма, шаг 1024. Терабайт — не запас на будущее: качая
/// плейлист целиком, за него выходят уже сегодня, а без верхней единицы
/// такой размер показывался бы как «5120.0 ГБ» — число, которое глазами
/// не читается.
const BYTE_UNITS: [&str; 5] = ["Б", "КБ", "МБ", "ГБ", "ТБ"];

/// Подбирает единицу под значение: делит на 1024, пока влезает.
///
/// Общая часть `human_bytes` и `human_speed`: шкала у них одна, и разъезжаться
/// ей нельзя. Стоит одной из функций остановиться на единицу раньше — и рядом
/// окажутся «5.0 ГБ из 10.0 ГБ» и «5120.0 МБ/с», числа одного порядка,
/// выглядящие как разные.
///
/// Не число и не положительное значение схлопываются в ноль: делить на 1024
/// такое бессмысленно, а до цикла эти случаи всё равно надо отсечь, иначе
/// `NaN >= 1024.0` даёт `false` и NaN уходит прямиком в вывод.
fn scale_bytes(value: f64) -> (f64, usize) {
    let mut value = if value.is_finite() && value > 0.0 {
        value
    } else {
        0.0
    };
    let mut unit = 0;
    while value >= 1024.0 && unit < BYTE_UNITS.len() - 1 {
        value /= 1024.0;
        unit += 1;
    }
    (value, unit)
}

pub fn human_bytes(bytes: u64) -> String {
    let (value, unit) = scale_bytes(bytes as f64);
    if unit == 0 {
        format!("{bytes} {}", BYTE_UNITS[0])
    } else {
        format!("{value:.1} {}", BYTE_UNITS[unit])
    }
}

/// Скорость загрузки: байты в секунду вместе с единицей, готовые к показу.
///
/// Отдельная функция, а не `human_bytes(speed as u64)` на стороне UI: у
/// скорости своя размерность («/с»), и собирать её из двух кусков в кадре
/// незачем. Плюс `as`-приведение отбрасывает дробную часть, и на медленном
/// соединении 0.9 Б/с превращались в «0 Б/с» — то есть в «встало», хотя
/// загрузка идёт.
pub fn human_speed(bytes_per_sec: f64) -> String {
    let (value, unit) = scale_bytes(bytes_per_sec);
    if unit == 0 {
        format!("{value:.0} {}/с", BYTE_UNITS[0])
    } else {
        format!("{value:.1} {}/с", BYTE_UNITS[unit])
    }
}

pub fn human_duration(secs: u64) -> String {
    let (h, m, s) = (secs / 3600, (secs % 3600) / 60, secs % 60);
    if h > 0 {
        format!("{h}:{m:02}:{s:02}")
    } else {
        format!("{m}:{s:02}")
    }
}

